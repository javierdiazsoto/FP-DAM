    private void itemBorrarJocActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_itemBorrarJocActionPerformed
        if (videojuegos.isEmpty()) {
    JOptionPane.showMessageDialog(this, "No hi ha cap joc per eliminar.");
    return;
}

String[] titulos = new String[videojuegos.size()];


    if (videojuegos.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "No hi ha cap joc per eliminar."
        );
        return;
    }


    for (int i = 0; i < videojuegos.size(); i++) {
        titulos[i] = videojuegos.get(i).getTitulo();
    }

    String seleccionado = (String) JOptionPane.showInputDialog(
            this,
            "Selecciona el joc que vols eliminar:",
            "Eliminar joc",
            JOptionPane.QUESTION_MESSAGE,
            null,
            titulos,
            titulos[0]
    );

    if (seleccionado == null) {
        return;
    }

    // Comprovar si el videojoc té lloguers pendents
    for (int i = 0; i < tablaLloguers.getRowCount(); i++) {

        if (seleccionado.equals(tablaLloguers.getValueAt(i, 1))
                && "Pendent".equals(tablaLloguers.getValueAt(i, 7))) {

            JOptionPane.showMessageDialog(
                    this,
                    "No es pot eliminar el joc perquè té un lloguer actiu."
            );
            return;
        }
    }

    // Eliminar el videojoc
    for (int i = 0; i < videojuegos.size(); i++) {

        if (videojuegos.get(i).getTitulo().equals(seleccionado)) {
            videojuegos.remove(i);
            break;
        }
    }

    JOptionPane.showMessageDialog(
            this,
            "Joc eliminat correctament."
    );

    }//GEN-LAST:event_itemBorrarJocActionPerformed

