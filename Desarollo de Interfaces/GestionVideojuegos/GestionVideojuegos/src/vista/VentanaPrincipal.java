    private void itemCrearJocActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_itemCrearJocActionPerformed
      String titulo = JOptionPane.showInputDialog(this, "Introdueix el títol del joc:");

if (titulo == null || titulo.trim().isEmpty()) {
    return;
}

String genero = JOptionPane.showInputDialog(this, "Introdueix el gènere del joc:");

if (genero == null || genero.trim().isEmpty()) {
    return;
}

modelo.Videojuego nuevoJuego = new modelo.Videojuego(titulo, genero);
videojuegos.add(nuevoJuego);
String[] plataformas = {"PS5", "Switch 2", "Xbox", "PC"};

for (String plataforma : plataformas) {
    String unidades = JOptionPane.showInputDialog(
            this, "Quantes unitats hi ha de " + plataforma + "?");

    if (unidades == null) {
        return;
    }

    try {
        int stock = Integer.parseInt(unidades);

        if (stock < 0) {
            JOptionPane.showMessageDialog(this, "Introdueix un nombre vàlid.");
            return;
        }

        nuevoJuego.agregarPlataforma(plataforma, stock);

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Introdueix un nombre vàlid.");
        return;
    }
}

  JOptionPane.showMessageDialog(this, "Joc creat correctament.");
    }//GEN-LAST:event_itemCrearJocActionPerformed

