    private void itemTornarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_itemTornarActionPerformed
   int fila = tablaLloguers.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this,
                "Selecciona un lloguer per retornar.");
        return;
    }

    if (fila >= alquileres.size()) {
        JOptionPane.showMessageDialog(this,
                "No s'ha trobat el lloguer.");
        return;
    }

    modelo.Alquiler alquilerSeleccionado = alquileres.get(fila);

    if (alquilerSeleccionado.isDevuelto()) {
        JOptionPane.showMessageDialog(this,
                "Aquest lloguer ja s'ha retornat.");
        return;
    }

    alquilerSeleccionado.devolver();

    alquilerSeleccionado.getVideojuego().modificarStock(
            alquilerSeleccionado.getPlataforma(), 1);

    javax.swing.table.DefaultTableModel tabla =
            (javax.swing.table.DefaultTableModel) tablaLloguers.getModel();

    tabla.setValueAt("Retornat", fila, 7);

  int totalActivos = 0;

for (int i = 0; i < tabla.getRowCount(); i++) {
    if ("Pendent".equals(tabla.getValueAt(i, 7))) {
        totalActivos++;
    }
}

lblTotalLloguers.setText("Total de lloguers: " + totalActivos);

    tablaLloguers.repaint();

    JOptionPane.showMessageDialog(this,
            "El lloguer s'ha retornat correctament.");
    }//GEN-LAST:event_itemTornarActionPerformed

    private void jMenuItem1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem1ActionPerformed
        if (videojuegos.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Primer has de crear un joc.");
    return;
}

String[] titulos = new String[videojuegos.size()];

for (int i = 0; i < videojuegos.size(); i++) {
    titulos[i] = videojuegos.get(i).getTitulo();
}

String titulo = (String) JOptionPane.showInputDialog(
        this,
        "Selecciona un joc:",
        "Registrar lloguer",
        JOptionPane.QUESTION_MESSAGE,
        null,
        titulos,
        titulos[0]
);

if (titulo == null) {
    return;
}
if (titulo == null) {
    return;
}

if (usuarios.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Primer has de crear un usuari.");
    return;
}

String[] nombresUsuarios = new String[usuarios.size()];

for (int i = 0; i < usuarios.size(); i++) {
    nombresUsuarios[i] = usuarios.get(i).getNombre();
}

String usuario = (String) JOptionPane.showInputDialog(
        this,
        "Selecciona un usuari:",
        "Registrar lloguer",
        JOptionPane.QUESTION_MESSAGE,
        null,
        nombresUsuarios,
        nombresUsuarios[0]
);

if (usuario == null) {
    return;
}

modelo.Videojuego juegoSeleccionado = null;

for (modelo.Videojuego juego : videojuegos) {
    if (juego.getTitulo().equals(titulo)) {
        juegoSeleccionado = juego;
        break;
    }
}

String[] plataformas = {"PS5", "Switch 2", "Xbox", "PC"};
java.util.ArrayList<String> disponibles = new java.util.ArrayList<>();

for (String plataforma : plataformas) {
    if (juegoSeleccionado.getUnidadesDisponibles(plataforma) > 0) {
        disponibles.add(plataforma);
    }
}

if (disponibles.isEmpty()) {
    JOptionPane.showMessageDialog(this, "No hi ha estoc disponible.");
    return;
}

String plataforma = (String) JOptionPane.showInputDialog(
        this,
        "Selecciona una plataforma:",
        "Registrar lloguer",
        JOptionPane.QUESTION_MESSAGE,
        null,
        disponibles.toArray(),
        disponibles.get(0)
);

if (plataforma == null) {
    return;
}
juegoSeleccionado.modificarStock(plataforma, -1);
    javax.swing.table.DefaultTableModel tabla =
        (javax.swing.table.DefaultTableModel) tablaLloguers.getModel();
modelo.Usuario usuarioSeleccionado = null;

for (modelo.Usuario u : usuarios) {
    if (u.getNombre().equals(usuario)) {
        usuarioSeleccionado = u;
        break;
    }
}

int numeroRegistro = tabla.getRowCount() + 1;

modelo.Alquiler nuevoAlquiler = new modelo.Alquiler(
        numeroRegistro,
        usuarioSeleccionado,
        juegoSeleccionado,
        plataforma
);

alquileres.add(nuevoAlquiler);

tabla.addRow(new Object[]{
    tabla.getRowCount() + 1,
    titulo,
    usuario,
    plataforma,
    java.time.LocalDate.now(),
    java.time.LocalDate.now().plusDays(7),
    juegoSeleccionado.getGenero(),
    "Pendent"
});

int totalActivos = 0;

for (int i = 0; i < tabla.getRowCount(); i++) {
    if ("Pendent".equals(tabla.getValueAt(i, 7))) {
        totalActivos++;
    }
}

lblTotalLloguers.setText("Total de lloguers: " + totalActivos);

JOptionPane.showMessageDialog(this, "Lloguer registrat correctament.");
    }//GEN-LAST:event_jMenuItem1ActionPerformed

    
